"""Backfill SYNTHETIC queue history for the demo offices so analytics, the demand forecast and the model
benchmark have something to show.

    python scripts/seed_history.py              # last 28 days for every active office
    python scripts/seed_history.py --days 14
    python scripts/seed_history.py --force      # replace previously seeded history

Tokens are generated by app/ml/simulator.py (peak hours, weekday effects, breaks, no-shows, ...) and use no
citizen account (citizen_id is NULL), which is how they can be told apart from real tokens. Each served token also
gets prediction snapshots (baseline and, when a trained model exists, ML) so the Models page can report
out-of-sample error. This is demo data; label it as such when presenting.
"""
import argparse
import math
import sys
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402
from sqlalchemy import delete, select  # noqa: E402

from app.db.models import Counter, Office, PredictionSnapshot, Service, Token  # noqa: E402
from app.db.session import SessionLocal  # noqa: E402
from app.ml import eta_model  # noqa: E402
from app.ml.simulator import CounterCfg, OfficeCfg, ServiceCfg, simulate  # noqa: E402
from app.services.timeutil import office_local_date, office_tz  # noqa: E402

SEED = 2026


def _stamp(day: date, minutes: float | None, tz) -> datetime | None:
    if minutes is None:
        return None
    local = datetime.combine(day, time(0), tzinfo=tz) + timedelta(minutes=minutes)
    return local.astimezone(timezone.utc)


def seed_office(session, office: Office, days: int, force: bool, rng: np.random.RandomState) -> tuple[int, int]:
    existing = session.scalar(select(Token.id).where(Token.office_id == office.id, Token.citizen_id.is_(None)).limit(1))
    if existing is not None:
        if not force:
            return 0, 0
        ids = select(Token.id).where(Token.office_id == office.id, Token.citizen_id.is_(None))
        session.execute(delete(PredictionSnapshot).where(PredictionSnapshot.token_id.in_(ids)))
        session.execute(delete(Token).where(Token.office_id == office.id, Token.citizen_id.is_(None)))
        session.flush()

    services = list(session.scalars(select(Service).where(Service.office_id == office.id, Service.is_active.is_(True))
                                    .order_by(Service.code)))
    counters = list(session.scalars(select(Counter).where(Counter.office_id == office.id).order_by(Counter.name)))
    if not services or not counters:
        return 0, 0
    sidx = {s.id: i for i, s in enumerate(services)}
    cfg = OfficeCfg(
        name=office.name,
        open_min=(office.opening_time.hour * 60 + office.opening_time.minute) if office.opening_time else 9 * 60 + 30,
        close_min=(office.closing_time.hour * 60 + office.closing_time.minute) if office.closing_time else 17 * 60 + 30,
        services=[ServiceCfg(code=s.code, configured=float(s.estimated_service_minutes),
                             true_mean=float(s.estimated_service_minutes) * float(rng.uniform(1.0, 1.5)))
                  for s in services],
        counters=[CounterCfg(service=sidx.get(c.service_id), speed=float(rng.uniform(0.9, 1.2))) for c in counters],
        demand=float(rng.uniform(0.75, 0.95)))

    today = office_local_date(office)
    taken = set(session.scalars(select(Token.queue_date).where(Token.office_id == office.id).distinct()))
    day_list = [today - timedelta(days=d) for d in range(days, 0, -1) if (today - timedelta(days=d)) not in taken]
    tz = office_tz(office)
    tokens = simulate(cfg, day_list, rng)

    rows, snap_meta = [], []
    for t in tokens:
        svc = services[t["service"]]
        tok = Token(display_number=f"{svc.code}-{t['number']:03d}", citizen_id=None, office_id=office.id,
                    service_id=svc.id, counter_id=counters[t["counter"]].id if t["counter"] is not None else None,
                    queue_date=t["date"], queue_number=t["number"], status=t["status"],
                    created_at=_stamp(t["date"], t["created"], tz), called_at=_stamp(t["date"], t["called"], tz),
                    service_started_at=_stamp(t["date"], t["start"], tz),
                    completed_at=_stamp(t["date"], t["complete"], tz),
                    updated_at=_stamp(t["date"], t["complete"] or t["called"] or t["created"], tz))
        rows.append(tok)
        if t["status"] == "COMPLETED" and "features" in t:
            snap_meta.append((tok, t))
    session.add_all(rows)
    session.flush()

    preds = eta_model.predict([t["features"] for _, t in snap_meta]) if snap_meta else None
    snaps = 0
    for i, (tok, t) in enumerate(snap_meta):
        w = t["baseline_wait"]
        session.add(PredictionSnapshot(
            office_id=office.id, service_id=tok.service_id, token_id=tok.id, predicted_wait_minutes=w,
            lower_minutes=max(0, math.floor(w * 0.75)), upper_minutes=max(math.ceil(w * 1.5), w + 2),
            queue_position=int(t["features"][0]) + 1, method="BASELINE", generated_at=tok.created_at))
        snaps += 1
        if preds is not None:
            mean, lo, hi = preds[i]
            session.add(PredictionSnapshot(
                office_id=office.id, service_id=tok.service_id, token_id=tok.id,
                predicted_wait_minutes=round(mean), lower_minutes=math.floor(lo), upper_minutes=max(math.ceil(hi), round(mean)),
                queue_position=int(t["features"][0]) + 1, method="ML", model_version=eta_model.version(),
                generated_at=tok.created_at))
            snaps += 1
    return len(rows), snaps


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=28)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    rng = np.random.RandomState(SEED)
    with SessionLocal() as session:
        for office in session.scalars(select(Office).where(Office.is_active.is_(True)).order_by(Office.name)).all():
            n, s = seed_office(session, office, args.days, args.force, rng)
            session.commit()
            print(f"{office.name}: {n} tokens, {s} prediction snapshots" if n else
                  f"{office.name}: skipped (history exists; use --force to replace)")
    if not eta_model.available():
        print("Note: no trained ETA model found, only baseline snapshots were written (run scripts/train_eta_model.py).")


if __name__ == "__main__":
    main()
